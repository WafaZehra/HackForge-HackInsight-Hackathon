def md_table(df: pd.DataFrame, formats: dict[str, str] | None = None) -> str:
    formats = formats or {}
    head = "| " + " | ".join(df.columns) + " |\n|" + "---|" * len(df.columns) + "\n"
    rows = []
    for _, r in df.iterrows():
        cells = []
        for c in df.columns:
            v = r[c]
            if isinstance(v, (float, np.floating)):
                cells.append("n/a" if np.isnan(v) else format(v, formats.get(c, ".2f")))
            else:
                cells.append(str(v))
        rows.append("| " + " | ".join(cells) + " |")
    return head + "\n".join(rows)


def warehouse_info(db_path) -> dict:
    con = duckdb.connect(str(db_path), read_only=True)
    try:
        run = con.execute("SELECT run_id, fact_rows, fact_content_hash FROM meta_pipeline_run ORDER BY finished_utc DESC LIMIT 1").fetchone()
        gold = con.execute("SELECT count(*) FROM gold_station_daily").fetchone()[0]
    finally:
        con.close()
    return {"pipeline_run_id": run[0], "fact_rows": int(run[1]), "fact_content_hash": run[2], "gold_station_daily_rows": int(gold)}


def build_card(ctx: dict) -> str:
    o, boot, split = ctx["overall"], ctx["bootstrap"], ctx["split"]
    beats = o["skill_vs_baseline"] > 0 and boot["mae_gain_ci_low"] > 0
    verdict = ("The model beats the declared baseline: the 95% interval for the MAE gain is above zero."
               if beats else "The model does NOT clearly beat the declared baseline: the 95% interval for the MAE gain includes zero or is negative.")
    city = ctx["by_city"]
    weakest_skill = city.sort_values("skill_vs_baseline").iloc[0]
    weakest_rel = city.sort_values("rel_mae_model", ascending=False).iloc[0]
    nominal = 1 - C.INTERVAL_ALPHA
    under_city = city[city["coverage"] < nominal - 0.05]
    under_city_txt = ", ".join(f"{r.city} ({r.coverage * 100:.1f}%)" for r in under_city.itertuples()) or "none"
    worse_city = city[city["skill_vs_baseline"] <= 0]
    worse_city_txt = ", ".join(f"{r.city} ({r.skill_vs_baseline * 100:.1f}%)" for r in worse_city.itertuples()) or "none"
    under_lvl = ctx["by_level"][ctx["by_level"]["coverage"] < nominal - 0.05]
    under_lvl_txt = ", ".join(f"{r.level} ({r.coverage * 100:.1f}%)" for r in under_lvl.itertuples()) or "none"
    grid_sorted = ctx["grid"].sort_values("cv_mae")
    grid_spread = float(grid_sorted["cv_mae"].iloc[min(2, len(grid_sorted) - 1)] - grid_sorted["cv_mae"].iloc[0])
    overall_tbl = pd.DataFrame([
        {"forecast": "baseline: persistence (tomorrow = today), declared", "MAE": o["mae_baseline"], "RMSE": o["rmse_baseline"], "bias": o["bias_baseline"]},
        {"forecast": "reference: same weekday last week", "MAE": o["mae_seasonal7"], "RMSE": o["rmse_seasonal7"], "bias": o["bias_seasonal7"]},
        {"forecast": "model: gradient boosting", "MAE": o["mae_model"], "RMSE": o["rmse_model"], "bias": o["bias_model"]},
    ])
    city_tbl = city[["city", "n", "mean_actual", "mae_baseline", "mae_model", "skill_vs_baseline", "rel_mae_model", "coverage", "mean_width"]].copy()
    city_tbl["skill_vs_baseline"] *= 100
    city_tbl["rel_mae_model"] *= 100
    city_tbl["coverage"] *= 100
    city_tbl.columns = ["city", "n", "mean PM2.5", "MAE baseline", "MAE model", "skill %", "MAE / mean %", "coverage %", "interval width"]
    lvl = ctx["by_level"][["level", "n", "mae_baseline", "mae_model", "bias_model", "coverage"]].copy()
    lvl["coverage"] *= 100
    lvl.columns = ["actual level", "n", "MAE baseline", "MAE model", "model bias", "coverage %"]
    month = ctx["by_month"][["month", "n", "mean_actual", "mae_baseline", "mae_model", "skill_vs_baseline"]].copy()
    month["skill_vs_baseline"] *= 100
    month.columns = ["month", "n", "mean PM2.5", "MAE baseline", "MAE model", "skill %"]
    season = ctx["backtest_season"][["season", "n", "mean_actual", "mae_baseline", "mae_model", "skill_vs_baseline", "coverage"]].copy()
    season["skill_vs_baseline"] *= 100
    season["coverage"] *= 100
    season.columns = ["season", "n", "mean PM2.5", "MAE baseline", "MAE model", "skill %", "coverage %"]
    alert = pd.DataFrame([
        {"forecast": "baseline", "precision": o["alert_precision_baseline"], "recall": o["alert_recall_baseline"], "F1": o["alert_f1_baseline"]},
        {"forecast": "model", "precision": o["alert_precision_model"], "recall": o["alert_recall_model"], "F1": o["alert_f1_model"]},
    ])
    imp = ctx["importance"].head(8)[["feature", "mae_increase"]]
    wh = ctx["warehouse"]
    return f"""# Model card: next-day PM2.5 forecast

Generated by `python -m src.model_run` at {ctx['finished_utc']}. Every number below is computed by code from the files in this folder.

## What is predicted
- Target: the 24-hour mean PM2.5 (ug/m3, PKT day) of the next day for each station, from `gold_station_daily`.
- Forecast is made at the end of day t using only data up to day t (lags, rolling means, other pollutants, calendar, station location).
- Primary user and decision: a city or district air-quality officer deciding which cities to warn one day ahead.
- Declared baseline (fixed in `src/config.py` before any result existed): `{C.BASELINE}`, tomorrow equals today. Primary metric: MAE in ug/m3.

## Data and split
- Warehouse run `{wh['pipeline_run_id']}`, content hash `{wh['fact_content_hash']}`, {wh['fact_rows']:,} hourly rows, {wh['gold_station_daily_rows']:,} station-days.
- Series used: {ctx['n_series']} unique primary series in {ctx['n_cities']} cities. Rows with a missing target or baseline are excluded from evaluation ({ctx['n_dropped']} test rows).
- Split by time. Final test: target dates {split['test_start']} to {split['last_target']} ({ctx['test_rows']:,} station-days), untouched until the end.
- Tuning and calibration use {C.CV_FOLDS} rolling-origin blocks of {C.CV_BLOCK_DAYS} days before the test period; each block is predicted by a model trained only on earlier days.
- Training rows for the final model: target dates before {split['test_start']} ({ctx['train_rows']:,} rows). Test rows are never used for fitting, tuning or calibration. No scalers or encoders are fitted on test data.
- Chosen hyperparameters (lowest mean cross-validated MAE): `{json.dumps(ctx['best_params'])}`. Seed {C.SEED}.

## Result on the final test
{md_table(overall_tbl)}

- Skill vs baseline (1 - MAE model / MAE baseline): {o['skill_vs_baseline'] * 100:.1f}%.
- Gain in MAE: {boot['mae_gain_mean']:.2f} ug/m3, 95% interval {boot['mae_gain_ci_low']:.2f} to {boot['mae_gain_ci_high']:.2f} (block bootstrap over {boot['days']} days, {C.BOOTSTRAP_BLOCK_DAYS}-day blocks). Skill 95% interval {boot['skill_ci_low'] * 100:.1f}% to {boot['skill_ci_high'] * 100:.1f}%.
- {verdict}

## Uncertainty
- Each forecast has an {int((1 - C.INTERVAL_ALPHA) * 100)}% prediction interval (quantile gradient boosting, widened by split-conformal calibration on out-of-fold errors, offset {ctx['qhat']:.2f} ug/m3).
- Empirical coverage on the test: {o['coverage'] * 100:.1f}% (before calibration: {o['coverage_raw'] * 100:.1f}%). Mean interval width: {o['mean_width']:.1f} ug/m3.
- Meaning for the user: on roughly {int((1 - C.INTERVAL_ALPHA) * 10)} days in 10 the actual value should fall inside the range. A wide range means the forecast is uncertain and the warning should be read more cautiously.

## Errors by group (test)
By city:

{md_table(city_tbl, {'n': '.0f'})}

- Lowest skill vs baseline: {weakest_skill['city']} ({weakest_skill['skill_vs_baseline'] * 100:.1f}%).
- Largest error relative to its own level: {weakest_rel['city']} (MAE is {weakest_rel['rel_mae_model'] * 100:.0f}% of its mean PM2.5).
- Cities where the model did not beat the baseline (skill at or below zero): {worse_city_txt}.
- Cities where the interval covered the actual value more than 5 points below the nominal {nominal * 100:.0f}%: {under_city_txt}.
- What a user should do: treat forecasts for those cities with extra caution and rely on the interval, not the single number.

By month:

{md_table(month, {'n': '.0f'})}

By actual pollution level:

{md_table(lvl, {'n': '.0f'})}

Levels where coverage fell more than 5 points below nominal: {under_lvl_txt}.

Alerts (day at or above {C.ALERT_THRESHOLD} ug/m3, WHO 2021 interim target 3 for 24-hour PM2.5; {int(o['alert_days'])} such station-days in the test):

{md_table(alert)}

## Errors by season (out-of-fold, before the test period)
These come from the rolling-origin blocks, so they show how the same approach behaved in other seasons. They were also used to pick hyperparameters, so treat them as indicative, not as a second test.

{md_table(season, {'n': '.0f'})}

## What drives the forecast
Permutation importance on the last out-of-fold block (increase in MAE when a feature is shuffled):

{md_table(imp, {'mae_increase': '.3f'})}

## Limits
- The test period ({split['test_start']} to {split['last_target']}) covers the monsoon and early autumn, when PM2.5 is lower than in winter. Skill in the smog season is shown only through the out-of-fold seasonal table.
- The data are model output (Open-Meteo Air Quality API, Copernicus CAMS), not ground-station readings, so errors are errors against that product, not against measured air.
- One source only. No weather inputs yet; adding independent weather data is the most likely way to improve it.
- Stations sharing a model grid cell were collapsed to one series, so the effective number of independent locations is {ctx['n_series']}.
- Forecast skill depends on persistence: when conditions change abruptly the model lags.
- The three best hyperparameter settings differ by {grid_spread:.2f} ug/m3 in cross-validated MAE, so the choice among them matters little.
- Outputs are information, not professional advice. For a health emergency contact official emergency services or a doctor.

## Files
`predictions_test.csv` (one row per station-day, with `feature_row_id` and `target_row_id` that point to `gold_station_daily` rows), `predictions_oof.csv`, `metrics_overall.json`, `metrics_by_city.csv`, `metrics_by_month.csv`, `metrics_by_level.csv`, `metrics_backtest_by_season.csv`, `bootstrap.json`, `tuning_grid.csv`, `feature_importance.csv`, `model.joblib`, `run_info.json`.
"""


def main() -> int:
    t0 = time.perf_counter()
    db = C.PROCESSED / C.WAREHOUSE_NAME
    if not db.exists():
        print("[model] warehouse not found. Run `python -m src.build` first.", file=sys.stderr)
        return 1
    try:
        sup = build_supervised(load_daily(db))
        split = M.make_split(sup)
        best, grid = M.tune(sup, split)
        oof, importance = M.out_of_fold(sup, split, best)
        qhat = M.cqr_offset(oof)

        train = M.train_rows(sup, split.test_start)
        test = M.window_rows(sup, split.test_start)
        assert train["target_date"].max() < test["target_date"].min(), "train/test overlap"
        assert train["date"].max() < split.test_start, "training features reach into the test period"

        models = M.fit_final(train, best)
        pred = M.predict_with_interval(models, test, qhat)
        ev = M.evaluation_set(pred)
        n_dropped = len(pred) - len(ev)
        oof_pred = oof.copy()
        oof_pred["lo"], oof_pred["hi"] = M.apply_interval(oof_pred["pred"].to_numpy(), oof_pred["lo_raw"].to_numpy(), oof_pred["hi_raw"].to_numpy(), qhat)
        oof_ev = M.evaluation_set(oof_pred)

        overall = M.summarize(ev)
        boot = M.block_bootstrap(ev)
        by_city = M.group_table(ev, "city")
        ev["month"] = ev["target_date"].dt.strftime("%Y-%m")
        ev["level"] = M.level_label(ev["y"])
        by_month = M.group_table(ev, "month")
        by_level = M.group_table(ev, "level")
        oof_ev["season"] = oof_ev["target_date"].dt.month.map(M.SEASONS)
        backtest_season = M.group_table(oof_ev, "season")

        finished = datetime.now(timezone.utc).isoformat(timespec="seconds")
        ctx = {
            "overall": overall, "bootstrap": boot, "by_city": by_city, "by_month": by_month, "by_level": by_level,
            "backtest_season": backtest_season, "importance": importance, "grid": grid, "best_params": best, "qhat": qhat,
            "split": {"test_start": f"{split.test_start:%Y-%m-%d}", "last_target": f"{split.last_target:%Y-%m-%d}"},
            "warehouse": warehouse_info(db), "finished_utc": finished, "n_series": int(sup["station_id"].nunique()),
            "n_cities": int(sup["city"].nunique()), "n_dropped": int(n_dropped), "test_rows": int(len(ev)), "train_rows": int(len(train)),
        }
        out = C.STAGING / "model"
        if out.parent.exists():
            shutil.rmtree(out, ignore_errors=True)
        out.mkdir(parents=True, exist_ok=True)
        keep = ["station_id", "city", "date", "target_date", "feature_row_id", "target_row_id", "y", "base_persistence_1d",
                "base_seasonal_7d", "pred", "lo", "hi", "lo_raw", "hi_raw"]
        ev[keep].rename(columns={"y": "actual"}).to_csv(out / "predictions_test.csv", index=False)
        oof_ev[keep + ["fold"]].rename(columns={"y": "actual"}).to_csv(out / "predictions_oof.csv", index=False)
        (out / "metrics_overall.json").write_text(json.dumps(overall, indent=2), encoding="utf-8")
        (out / "bootstrap.json").write_text(json.dumps(boot, indent=2), encoding="utf-8")
        by_city.to_csv(out / "metrics_by_city.csv", index=False)
        by_month.to_csv(out / "metrics_by_month.csv", index=False)
        by_level.to_csv(out / "metrics_by_level.csv", index=False)
        backtest_season.to_csv(out / "metrics_backtest_by_season.csv", index=False)
        grid.to_csv(out / "tuning_grid.csv", index=False)
        importance.to_csv(out / "feature_importance.csv", index=False)
        joblib.dump({"models": models, "qhat": qhat, "features": FEATURES, "params": best, "baseline": C.BASELINE}, out / "model.joblib")
        info = {**ctx["warehouse"], "finished_utc": finished, "seed": C.SEED, "baseline": C.BASELINE, "best_params": best,
                "qhat": qhat, "split": ctx["split"], "sklearn": sklearn.__version__, "pandas": pd.__version__,
                "seconds": round(time.perf_counter() - t0, 1)}
        (out / "run_info.json").write_text(json.dumps(info, indent=2), encoding="utf-8")
        (out / "model_card.md").write_text(build_card(ctx), encoding="utf-8")
        old = C.MODEL_DIR.with_name(C.MODEL_DIR.name + ".old")
        if old.exists():
            shutil.rmtree(old)
        if C.MODEL_DIR.exists():
            C.MODEL_DIR.rename(old)
        out.rename(C.MODEL_DIR)
        if old.exists():
            shutil.rmtree(old)
    except Exception as exc:
        print(f"\n[FAILED] {type(exc).__name__}: {exc}\nPrevious model outputs were kept.", file=sys.stderr)
        shutil.rmtree(C.STAGING / "model", ignore_errors=True)
        return 1

    o = overall
    print("\n=== make model: OK ===")
    print(f"warehouse hash    {ctx['warehouse']['fact_content_hash']}")
    print(f"split             train < {ctx['split']['test_start']} | test {ctx['split']['test_start']} -> {ctx['split']['last_target']} ({len(ev):,} station-days)")
    print(f"best params       {best}")
    print(f"MAE  baseline     {o['mae_baseline']:.2f}   seasonal7 {o['mae_seasonal7']:.2f}   model {o['mae_model']:.2f}  (ug/m3)")
    print(f"skill vs baseline {o['skill_vs_baseline'] * 100:.1f}%   gain CI95 [{boot['mae_gain_ci_low']:.2f}, {boot['mae_gain_ci_high']:.2f}]")
    print(f"interval coverage {o['coverage'] * 100:.1f}% (target {int((1 - C.INTERVAL_ALPHA) * 100)}%), width {o['mean_width']:.1f}")
    print(f"timings           {time.perf_counter() - t0:.0f}s  ->  {C.MODEL_DIR}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
